#!/usr/bin/env python3
"""Deterministic RV32E instruction cases with independent 32-bit Python oracle.

Expected results are precomputed, embedded as constants in the assembly,
not calculated by the RISC-V CPU using the same operation being tested.
"""
from __future__ import annotations
import csv, pathlib, random
ROOT=pathlib.Path(__file__).resolve().parents[1]
MASK=0xffffffff

def u(x): return x&MASK
def s(x):
    v=u(x)
    return v if v<0x80000000 else v-0x100000000

def result(op,a,b):
    a=u(a);b=u(b); n=b&31
    return u({
      'add':lambda:a+b,'sub':lambda:a-b,'sll':lambda:a<<n,
      'slt':lambda:int(s(a)<s(b)),'sltu':lambda:int(a<b),
      'xor':lambda:a^b,'srl':lambda:a>>n,'sra':lambda:s(a)>>n,
      'or':lambda:a|b,'and':lambda:a&b,
      'addi':lambda:a+s(b&0xfff if (b&0x800)==0 else (b&0xfff)|0xfffff000),
      'slti':lambda:int(s(a)<s((b&0xfff)|(-4096 if (b&0x800) else 0))),
      'sltiu':lambda:int(a<u((b&0xfff)|(-4096 if (b&0x800) else 0))),
      'xori':lambda:a^u((b&0xfff)|(-4096 if (b&0x800) else 0)),
      'ori':lambda:a|u((b&0xfff)|(-4096 if (b&0x800) else 0)),
      'andi':lambda:a&u((b&0xfff)|(-4096 if (b&0x800) else 0)),
      'slli':lambda:a<<n,'srli':lambda:a>>n,'srai':lambda:s(a)>>n
    }[op]())

# Include exact boundary operands and randomized adversarial patterns.
OPS_R=['add','sub','sll','slt','sltu','xor','srl','sra','or','and']
OPS_I=['addi','slti','sltiu','xori','ori','andi','slli','srli','srai']
V=[(0,0),(0xffffffff,1),(0x80000000,0x7fffffff),
   (0xaaaaaaaa,0x55555555),(0x12345678,31),
   (0x87654321,32),(0x80000000,0xffffffff),(0x7fffffff,0x80000000),
   (0x00000001,0x00000020),(0xffffffff,0)]
rng=random.Random(0xc7a10)
case_list=[]
# Two tests for every RV32E R instruction + 1 extra for shifts/compare.
for idx,op in enumerate(OPS_R):
    case_list.extend([(op,*V[idx%len(V)]),(op,*V[(idx+3)%len(V)])])
    if op in ('sll','srl','sra','slt','sltu'): case_list.append((op,*V[(idx+7)%len(V)]))
# All I operations with tricky immediate signs and shift widths.
for idx,op in enumerate(OPS_I):
    a=V[(idx+2)%len(V)][0]
    imm= [0,1,31] [idx%3] if op in ('slli','srli','srai') else [0,1,-1,-2048,2047][idx%5]
    case_list.append((op,a,imm))
    if op in ('slli','srli','srai','slti','sltiu','addi'):
        case_list.append((op,0x80000000,31 if 'i' in op and op in ('slli','srli','srai') else -1))
# Additional independent random R-type operands.
for i in range(35):
    op=OPS_R[i%len(OPS_R)]
    a=rng.getrandbits(32);b=rng.getrandbits(32)
    case_list.append((op,a,b))

header='''// Generated by tools/generate_isa_torture.py, do not edit manually.
// Test IDs 41+; each actual result is checked against Python oracle constants.
.section .text,"ax",@progbits
.globl v10_isa_torture
.option push
.option norvc
v10_isa_torture:
    addi sp,sp,-64
    sw ra,60(sp)
    sw s0,56(sp)
    sw s1,52(sp)
'''
source=[header]
rows=[]
number=41
for op,a,b in case_list:
    expect=result(op,a,b)
    source.append(f'    # ID={number} {op}({a:#010x}, {b:#010x}) => {expect:#010x}\n')
    source.append(f'    li t0,0x{u(a):08x}\n')
    if op in OPS_R:
        source.append(f'    li t1,0x{u(b):08x}\n    {op} t2,t0,t1\n')
    else:
        source.append(f'    {op} t2,t0,{b}\n')
    source.append(f'    li a0,{number}\n    li a5,0x{expect:08x}\n    bne t2,a5,.Lreturn\n')
    rows.append((number,op,f'{u(a):08X}',f'{u(b):08X}',f'{expect:08X}'))
    number+=1
# Real uncompressed control and memory instruction cases are already part
# of firmware/v10_isa.S. Here target the omitted compressed instruction forms.
source.append('''
    # Compressed test IDs 200..: explicit 16-bit instructions.
.option rvc
    c.nop
    c.li s0,-1
    li a0,200
    li a5,-1
    bne s0,a5,.Lreturn
    c.addi s0,1
    li a0,201
    bnez s0,.Lreturn
    c.addi4spn s0,sp,16
    addi t0,sp,16
    li a0,202
    bne s0,t0,.Lreturn
    li t0,0x89abcdef
    c.swsp t0,0(sp)
    c.lwsp t1,0(sp)
    li a0,203
    bne t0,t1,.Lreturn
    mv s1,t0
    c.sw s1,0(s0)
    c.lw s1,0(s0)
    li a0,204
    bne s1,t0,.Lreturn
    c.li s0,-8
    c.srai s0,2
    li a0,205
    li a5,-2
    bne s0,a5,.Lreturn
    c.li s0,-8
    c.srli s0,2
    li a0,206
    li a5,0x3ffffffe
    bne s0,a5,.Lreturn
    c.li s0,-1
    c.andi s0,7
    li a0,207
    li a5,7
    bne s0,a5,.Lreturn
    c.li s0,7
    c.li s1,3
    c.sub s0,s1
    li a0,208
    li a5,4
    bne s0,a5,.Lreturn
    c.xor s0,s1
    li a0,209
    li a5,7
    bne s0,a5,.Lreturn
    c.or s0,s1
    li a0,210
    li a5,7
    bne s0,a5,.Lreturn
    c.and s0,s1
    li a0,211
    li a5,3
    bne s0,a5,.Lreturn
    c.li s0,1
    c.slli s0,31
    li a0,212
    li a5,0x80000000
    bne s0,a5,.Lreturn
    c.li s1,12
    c.mv s0,s1
    li a0,213
    li a5,12
    bne s0,a5,.Lreturn
    c.add s0,s1
    li a0,214
    li a5,24
    bne s0,a5,.Lreturn
    c.lui s0,1
    li a0,215
    li a5,0x1000
    bne s0,a5,.Lreturn
    c.addi16sp sp,16
    c.addi16sp sp,-16
    li a0,216
    addi t0,sp,16
    c.addi4spn s0,sp,16
    bne s0,t0,.Lreturn
    c.li s0,0
    li a0,217
    c.beqz s0,.Lczero
    j .Lreturn
.Lczero:
    li a0,218
    c.bnez s0,.Lreturn
    c.li s0,1
    li a0,219
    c.bnez s0,.Lcnonzero
    j .Lreturn
.Lcnonzero:
    li a0,220
    c.beqz s0,.Lreturn
    li a0,221
    c.j .Lcj_ok
    j .Lreturn
.Lcj_ok:
    # Preserve caller RA on stack; compressed JAL must set PC+2.
    li a0,222
    c.jal .Lcjal_function
    j .Lcjal_after
.Lcjal_function:
    c.jr ra
.Lcjal_after:
    li a0,223
    la t0,.Lcjalr_function
    c.jalr t0
    j .Lcjalr_after
.Lcjalr_function:
    c.jr ra
.Lcjalr_after:
.option norvc
    # CSR instructions: zero-mask reads of read-only counters, and CSRRW
    # against mepc (restore before returning). Unsupported CSRs are not
    # assumed to implement a full privileged-mode ISA.
    csrrs t0,0xc00,zero
    csrrc t1,0xc00,zero
    csrrsi t2,0xc00,0
    csrrci a2,0xc00,0
    csrrs t1,0x341,zero
    li t0,0x100
    csrrw t2,0x341,t0
    csrrs t2,0x341,zero
    li a0,224
    li a5,0x100
    bne t2,a5,.Lrestore_mepc
    li t0,0x10
    csrrwi t2,0x341,16
    csrrs t2,0x341,zero
    li a0,225
    li a5,0x10
    bne t2,a5,.Lrestore_mepc
    # CSR-immediate edge cases use architectural zimm, never x16..x31 GPRs.
    csrrwi t2,0x341,30
    csrrs t2,0x341,zero
    li a0,226
    li a5,30
    bne t2,a5,.Lrestore_mepc
    csrrci t2,0x341,16
    csrrs t2,0x341,zero
    li a0,227
    li a5,14
    bne t2,a5,.Lrestore_mepc
    csrrsi t2,0x341,16
    csrrs t2,0x341,zero
    li a0,228
    li a5,30
    bne t2,a5,.Lrestore_mepc
    csrrsi t2,0x341,0
    csrrs t2,0x341,zero
    li a0,229
    li a5,30
    bne t2,a5,.Lrestore_mepc
    csrrci t2,0x341,0
    csrrs t2,0x341,zero
    li a0,230
    li a5,30
    bne t2,a5,.Lrestore_mepc
    li a0,0
.Lrestore_mepc:
    csrrw zero,0x341,t1
.Lreturn:
    lw ra,60(sp)
    lw s0,56(sp)
    lw s1,52(sp)
    addi sp,sp,64
    ret
.option pop
''')
# clang assembler only permits uimm5 0..31 in CSRRSI/CSRRWI, choose 16.
(ROOT/'firmware/v10_isa_torture.S').write_text(''.join(source))
with (ROOT/'docs/ISA_TORTURE_VECTOR_MAP.csv').open('w',newline='') as f:
    writer=csv.writer(f); writer.writerow(['id','opcode','operand_a_hex','operand_b_hex','expected_hex']);writer.writerows(rows)
print('Vector cases:',len(rows),'ID range 41..',number-1,'+ 26 compressed/CSR checks')
